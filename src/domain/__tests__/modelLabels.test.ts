/* =========================================================================
   Label-mapping and measured-performance tests.

   These read the evaluation reports generated by
   `services/inference/eval/evaluate.py`, so the numbers the UI shows a farmer
   cannot silently drift away from the numbers that were actually measured, and
   the class -> condition map is checked against the class list the exporter
   really received from the model.
   ========================================================================= */

/// <reference types="node" />
// The application tsconfig deliberately narrows `types` to `vite/client` so the
// browser code cannot reach for Node globals by accident. These suites run under
// Node (vitest), so they opt back in explicitly, here and nowhere else.

import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';

import {
  MEASURED_PERFORMANCE,
  MODEL_CLASS_TO_CONDITION,
  conditionForModelClass,
  measuredPerformance,
} from '../modelLabels';
import { CONDITIONS, hasImageModel } from '../knowledge';

const root = resolve(__dirname, '../../..');

function report(crop: string) {
  return JSON.parse(
    readFileSync(resolve(root, `services/inference/eval/${crop}_results.json`), 'utf8'),
  );
}

const CROPS = ['cotton', 'soybean'] as const;

describe('model class -> condition mapping', () => {
  it('covers exactly the classes the measured model reported, in any order', () => {
    for (const crop of CROPS) {
      const measured = report(crop);
      const mapped = Object.keys(MODEL_CLASS_TO_CONDITION[crop]).sort();
      expect(mapped).toEqual([...measured.classes].sort());
    }
  });

  it('maps every class to a condition that actually exists in the knowledge base', () => {
    for (const crop of CROPS) {
      for (const [className, conditionId] of Object.entries(MODEL_CLASS_TO_CONDITION[crop])) {
        expect(conditionId, `${crop}/${className}`).not.toBeNull();
        expect(
          CONDITIONS.some((c) => c.id === conditionId),
          `${crop}/${className} -> ${conditionId}`,
        ).toBe(true);
      }
    }
  });

  it('returns null for an unknown class instead of guessing a condition', () => {
    expect(conditionForModelClass('cotton', 'powdery mildew')).toBeNull();
    expect(conditionForModelClass('rice', 'bacterial blight')).toBeNull();
    expect(conditionForModelClass('cotton', null)).toBeNull();
  });

  it('keeps the published class spelling, including the repository typo', () => {
    // classes.json in the model repository lists "fussarium wilt"; the app must
    // display the class the model was actually trained on, not a corrected one.
    expect(MODEL_CLASS_TO_CONDITION.cotton['fussarium wilt']).toBe('cotton_fusarium_wilt');
  });

  it('marks cotton and soybean as the only model-backed crops', () => {
    expect(hasImageModel('cotton')).toBe(true);
    expect(hasImageModel('soybean')).toBe(true);
    expect(hasImageModel('tomato')).toBe(false);
    expect(hasImageModel('rice')).toBe(false);
  });
});

describe('measured performance matches the generated reports', () => {
  it('reproduces macro-F1, coverage and accuracy for each crop', () => {
    for (const crop of CROPS) {
      const measured = report(crop).metrics;
      const shown = MEASURED_PERFORMANCE[crop];
      expect(shown.macroF1).toBeCloseTo(measured.macroF1, 3);
      expect(shown.coverage).toBeCloseTo(measured.coverage, 3);
      expect(shown.accuracyIncludingAbstentions).toBeCloseTo(
        measured.accuracyIncludingAbstentionsAsErrors,
        3,
      );
      expect(shown.selectiveAccuracyAmongAnswered).toBeCloseTo(
        measured.selectiveAccuracyAmongAnswered,
        3,
      );
      expect(shown.supportedImages).toBe(measured.supportedImages);
    }
  });

  it('reproduces per-class support and recall for every class with samples', () => {
    for (const crop of CROPS) {
      const perClass = report(crop).metrics.perClass;
      for (const [name, measured] of Object.entries(perClass)) {
        const shown = MEASURED_PERFORMANCE[crop].perClass[name];
        expect(shown, `${crop}/${name}`).toBeDefined();
        expect(shown.support).toBe((measured as { support: number }).support);
        if (shown.recall !== null) {
          expect(shown.recall).toBeCloseTo((measured as { recall: number }).recall, 3);
        }
      }
    }
  });

  it('states the published claim beside the measurement, and they differ', () => {
    for (const crop of CROPS) {
      const shown = MEASURED_PERFORMANCE[crop];
      expect(shown.publishedTestAccuracy).not.toBeNull();
      // The whole reason this block exists in the UI.
      expect(shown.publishedTestAccuracy!).toBeGreaterThan(shown.macroF1);
      expect(shown.caveat.length).toBeGreaterThan(20);
    }
  });

  it('has no measured performance for a crop with no model', () => {
    expect(measuredPerformance('tomato')).toBeNull();
  });
});
